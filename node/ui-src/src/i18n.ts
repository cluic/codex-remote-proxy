const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, "zh-CN": zh };

export type Translator = (key: TranslationKey, variables?: Record<string, string | number>) => string;

export function createTranslator(locale: Locale): Translator {
  return (key, variables = {}) => Object.entries(variables).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    dictionaries[locale][key]
  );
}

export function readInitialLocale(): Locale {
  try {
    const stored = localStorage.getItem("crp.locale");
    if (stored === "en" || stored === "zh-CN") return stored;
    if (stored !== null) localStorage.removeItem("crp.locale");
  } catch {
    // Browser storage can be unavailable without blocking the local console.
  }
  const preferences = typeof navigator === "undefined"
    ? []
    : [
        ...(Array.isArray(navigator.languages) ? navigator.languages : []),
        navigator.language
      ];
  for (const preference of preferences) {
    if (typeof preference !== "string") continue;
    const normalized = preference.trim().toLowerCase();
    if (normalized === "zh" || normalized.startsWith("zh-") || normalized.startsWith("zh_")) {
      return "zh-CN";
    }
    if (normalized === "en" || normalized.startsWith("en-") || normalized.startsWith("en_")) {
      return "en";
    }
  }
  return "en";
}

export function persistLocale(locale: Locale): void {
  try {
    localStorage.setItem("crp.locale", locale);
  } catch {
    // The explicit selection still applies to the current in-memory session.
  }
}

export function formatDate(locale: Locale, value: string | null, includeSeconds = false): string {
  if (value === null) return "-";
  const parsed = new Date(value);
  if (Number.isNaN(parsed.valueOf())) return "-";
  return new Intl.DateTimeFormat(locale, {
    dateStyle: "medium",
    timeStyle: includeSeconds ? "medium" : "short"
  }).format(parsed);
}

export function formatNumber(locale: Locale, value: number): string {
  return new Intl.NumberFormat(locale).format(value);
}

export function formatCompactNumber(locale: Locale, value: number): string {
  return new Intl.NumberFormat(locale, { notation: "compact", maximumFractionDigits: 1 }).format(value);
}

export function formatPercent(locale: Locale, ratio: number): string {
  return new Intl.NumberFormat(locale, { style: "percent", maximumFractionDigits: 1 }).format(ratio);
}

export function formatDuration(locale: Locale, milliseconds: number | null): string {
  if (milliseconds === null) return "-";
  if (milliseconds < 1_000) return `${formatNumber(locale, milliseconds)} ms`;
  return `${new Intl.NumberFormat(locale, { maximumFractionDigits: 1 }).format(milliseconds / 1_000)} s`;
}
